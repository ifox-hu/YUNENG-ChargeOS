const assert = require('node:assert/strict');
const fs = require('node:fs');
const http = require('node:http');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/Lenovo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const { readDemoCaptcha } = require('./demo-captcha-helper.cjs');

(async () => {
  const root = path.resolve(__dirname, '../site');
  const server = http.createServer((req, res) => {
    const pathname = new URL(req.url, 'http://localhost').pathname.replace(/^\/site(?=\/|$)/, '');
    const file = path.resolve(root, '.' + (pathname === '/' ? '/index.html' : pathname));
    if (!file.startsWith(root + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) {
      res.writeHead(404); return res.end();
    }
    res.setHeader('Content-Type', file.endsWith('.js') ? 'text/javascript' : file.endsWith('.css') ? 'text/css' : file.endsWith('.svg') ? 'image/svg+xml' : file.endsWith('.png') ? 'image/png' : 'text/html');
    res.end(fs.readFileSync(file));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = process.env.DEMO_URL || 'http://127.0.0.1:' + server.address().port + '/site/';
  let browser;
  try {
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [], requests = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', r => { if (!r.url().startsWith(new URL(base).origin) && !r.url().startsWith('data:')) requests.push(r.url()); });
    await page.goto(base + '#/login');
    await readDemoCaptcha(page);
    assert.equal(await page.getByPlaceholder('请输入账号').inputValue(), 'admin');
    assert.equal(await page.getByPlaceholder('请输入密码').inputValue(), '');
    await page.locator('input[type="password"]').fill('Demo123456!');
    const submit = page.locator('.login-actions button');
    const code = page.getByPlaceholder('请输入右侧验证码');
    await submit.click();
    await page.getByText('请输入验证码', { exact: true }).waitFor();
    assert.equal((await page.context().cookies()).some(c => c.name === 'Demo-Token'), false);
    console.log('PASS empty captcha blocks login');
    const before = await page.locator('.login-code-img').getAttribute('src');
    await code.fill('0000');
    await code.press('Enter');
    await page.getByText('验证码错误，请重新输入', { exact: true }).waitFor();
    await page.waitForFunction(old => document.querySelector('.login-code-img').src !== old, before);
    assert.equal(await code.inputValue(), '');
    assert(page.url().endsWith('#/login'));
    assert.equal((await page.context().cookies()).some(c => c.name === 'Demo-Token'), false);
    console.log('PASS wrong captcha blocks login and refresh clears input');
    const previous = await page.locator('.login-code-img').getAttribute('src');
    await page.getByRole('button', { name: '刷新验证码' }).focus();
    await page.keyboard.press('Enter');
    await page.waitForFunction(old => document.querySelector('.login-code-img').src !== old, previous);
    await readDemoCaptcha(page);
    await page.locator('.el-message--error').waitFor({ state: 'hidden' });
    fs.mkdirSync(path.join(__dirname, '../outputs'), { recursive: true });
    await page.locator('.login').screenshot({ path: path.join(__dirname, '../outputs/pages-captcha-desktop.png') });
    await code.fill((await readDemoCaptcha(page)).toLowerCase());
    await code.press('Enter');
    await page.waitForURL('**/#/index');
    await page.locator('.sidebar-container').waitFor();
    console.log('PASS keyboard refresh and case-insensitive captcha login at subdirectory');
    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } });
    await mobile.goto(base + '#/login');
    await readDemoCaptcha(mobile);
    const mobilePassword = mobile.getByPlaceholder('请输入密码');
    const mobileCode = mobile.getByPlaceholder('请输入右侧验证码');
    const fillDemo = mobile.getByRole('button', { name: '一键填入', exact: true });
    assert.equal(await mobilePassword.inputValue(), '');
    await fillDemo.click();
    assert.equal(await mobilePassword.inputValue(), 'Demo123456!');
    assert.equal(await mobileCode.inputValue(), await readDemoCaptcha(mobile));
    assert.equal((await mobile.context().cookies()).some(cookie => cookie.name === 'Demo-Token'), false);
    const staleChallenge = await mobile.locator('.login-code-img').getAttribute('src');
    await mobile.clock.setFixedTime(new Date(Date.now() + 121000));
    await fillDemo.click();
    await mobile.waitForFunction(previous => document.querySelector('.login-code-img').src !== previous, staleChallenge);
    assert.equal(await mobileCode.inputValue(), await readDemoCaptcha(mobile));
    console.log('PASS one-click fill leaves submit to the user and renews an expired challenge');
    assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    const bounds = await mobile.locator('.field__row').boundingBox();
    assert(bounds.width > 116 && bounds.x >= 0 && bounds.x + bounds.width <= 390, JSON.stringify(bounds));
    await mobile.screenshot({ path: path.join(__dirname, '../outputs/pages-captcha-mobile.png'), fullPage: true });
    await mobileCode.press('Enter');
    await mobile.waitForURL('**/#/index');
    await mobile.locator('.sidebar-container').waitFor();
    const cold = await browser.newPage();
    let dashboardRequests = 0;
    const adminEntry = '**/static/js/admin.*.js';
    await cold.route('**/vendor/three-r160.min.js', route => route.abort());
    await cold.route(adminEntry, route => {
      dashboardRequests++;
      return route.abort();
    });
    await cold.goto(base + '#/operate/station');
    const coldCode = cold.getByPlaceholder('请输入右侧验证码');
    await cold.getByPlaceholder('请输入账号').fill('demo');
    await cold.getByPlaceholder('请输入密码').fill('Demo123456!');
    assert.equal(dashboardRequests, 0);
    await coldCode.fill(await readDemoCaptcha(cold));
    const firstChallenge = await cold.locator('.login-code-img').getAttribute('src');
    await coldCode.press('Enter');
    await cold.getByText('后台加载失败，请重试', { exact: true }).waitFor();
    assert.equal(dashboardRequests, 1);
    assert.equal((await cold.context().cookies()).some(cookie => cookie.name === 'Demo-Token'), false);
    await cold.waitForFunction(previous => document.querySelector('.login-code-img').src !== previous, firstChallenge);
    await cold.unroute(adminEntry);
    await coldCode.fill(await readDemoCaptcha(cold));
    await coldCode.press('Enter');
    await cold.waitForURL('**/#/operate/station');
    await cold.locator('.sidebar-container').waitFor();
    console.log('PASS cold form works without WebGL or dashboard; failed chunk retries and preserves the deep link');
    assert.deepEqual(errors, []);
    assert.deepEqual(requests, []);
    console.log('PASS mobile layout; no external requests or page errors');
  } finally {
    if (browser) await browser.close();
    server.close();
  }
})().catch(e => { console.error(e); process.exitCode = 1; });
