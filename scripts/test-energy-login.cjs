const assert = require('node:assert/strict')
const fs = require('node:fs')
const http = require('node:http')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Program Files/WindowsApps/OpenAI.CodexPrimaryRuntime.v26-1112-737-0_26.1112.737.0_x64__3k8sg7r9htsxt/dependencies/node/node_modules/playwright')
const { fillDemoCaptcha } = require('./demo-captcha-helper.cjs')

;(async () => {
  const root = path.resolve(process.env.ENERGY_SITE_ROOT || path.join(__dirname, '../site'))
  const server = http.createServer((req, res) => {
    const pathname = new URL(req.url, 'http://localhost').pathname.replace(/^\/site(?=\/|$)/, '')
    const file = path.resolve(root, '.' + (pathname === '/' ? '/index.html' : pathname))
    if (!file.startsWith(root + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) { res.writeHead(404); return res.end() }
    res.setHeader('Content-Type', file.endsWith('.js') ? 'text/javascript' : file.endsWith('.css') ? 'text/css' : file.endsWith('.svg') ? 'image/svg+xml' : file.endsWith('.png') ? 'image/png' : 'text/html')
    res.end(fs.readFileSync(file))
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const url = process.env.ENERGY_URL || 'http://127.0.0.1:' + server.address().port + '/site/#/login'
  const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
  const output = path.join(__dirname, '../outputs')
  fs.mkdirSync(output, { recursive: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('console', m => { if (m.type() === 'error' && /shader|WebGLProgram/.test(m.text())) errors.push(m.text()) })
    await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 })
    await page.locator('.ec-ready canvas').waitFor({ timeout: 60000 })
    const stage = page.locator('.ec-stage'), hit = page.locator('.ec-core-hit')
    const getState = () => stage.evaluate(el => ({ ...el.dataset }))
    const resolution = await page.locator('.ec-stage canvas').evaluate(c => c.width / c.clientWidth)
    assert(resolution >= 1.99)
    assert.equal(await page.locator('.ec-scene-tools').count(), 0)
    const box = await hit.boundingBox(), x = box.x + box.width * .45, y = box.y + box.height * .5
    const initial = await getState()
    await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + 125, y - 60, { steps: 12 }); await page.mouse.up()
    await page.waitForTimeout(200)
    const after = await getState()
    assert.notEqual(initial.rotation, after.rotation)
    assert.equal(after.pulse, undefined)
    await page.waitForTimeout(250)
    assert.notEqual((await getState()).rotation, after.rotation)
    await hit.click({ position: { x: box.width * .45, y: box.height * .5 } })
    assert.equal((await getState()).pulse, '1')
    await page.mouse.wheel(0, -120); await page.waitForTimeout(600)
    assert(Number((await getState()).zoom) > 1)
    await hit.focus(); await page.keyboard.press('Home'); await page.waitForTimeout(650)
    await page.screenshot({ path: path.join(output, 'energy-login-desktop.png'), fullPage: true })
    const layout = () => page.evaluate(() => {
      const panel = document.querySelector('.ec-panel-shell').getBoundingClientRect()
      const footer = document.querySelector('.ec-footer').getBoundingClientRect()
      return { overflow: document.documentElement.scrollWidth > innerWidth, overlap: panel.bottom > footer.top, panelLeft: panel.left, panelRight: panel.right, width: innerWidth }
    })
    for (const width of [1440, 1024, 736, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 }); await page.waitForTimeout(100)
      const result = await layout()
      assert(!result.overflow && !result.overlap && result.panelLeft >= 0 && result.panelRight <= width, JSON.stringify(result))
    }
    await page.screenshot({ path: path.join(output, 'energy-login-mobile.png'), fullPage: true })
    await page.setViewportSize({ width: 1440, height: 1000 })
    if (!process.env.ENERGY_URL) {
      await page.getByPlaceholder('请输入账号').fill('demo')
      await page.getByPlaceholder('请输入密码').fill('Demo123456!')
      await fillDemoCaptcha(page)
      await page.locator('.login-actions button').click()
      await page.waitForURL('**/#/index')
      assert.equal(await page.locator('.ec-stage canvas').count(), 0)
      await page.locator('.avatar-wrapper').click()
      await page.getByText('退出登录', { exact: true }).click()
      await page.getByRole('button', { name: '确定', exact: true }).click()
      await page.waitForURL('**/#/login')
      await page.locator('.ec-ready canvas').waitFor()
      assert.equal(await page.locator('.ec-stage canvas').count(), 1)
    }
    const blocked = await browser.newPage()
    await blocked.route('**/vendor/three-r160.min.js', route => route.abort())
    await blocked.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 })
    await blocked.getByText('能量核心 · 静态展示', { exact: true }).waitFor()
    assert(await blocked.locator('.ec-fallback').isVisible())
    assert(await blocked.locator('.login-actions button').isEnabled())
    await blocked.close()
    assert.deepEqual(errors, [])
    console.log('PASS HD canvas; drag/inertia/click/zoom; 1440/1024/736/390/320 layouts; ' + (process.env.ENERGY_URL ? '' : 'login/logout remount; ') + 'runtime failure fallback; no page/shader errors')
  } finally { await browser.close(); server.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
