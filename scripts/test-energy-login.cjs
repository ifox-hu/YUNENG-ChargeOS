const assert = require('node:assert/strict')
const fs = require('node:fs')
const http = require('node:http')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/Lenovo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const { fillDemoCaptcha } = require('./demo-captcha-helper.cjs')

;(async () => {
  const root = path.resolve(process.env.ENERGY_SITE_ROOT || path.join(__dirname, '../site'))
  const server = http.createServer((req, res) => {
    const pathname = new URL(req.url, 'http://localhost').pathname.replace(/^\/site(?=\/|$)/, '')
    const file = path.resolve(root, '.' + (pathname === '/' ? '/index.html' : pathname))
    if (!file.startsWith(root + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) { res.writeHead(404); return res.end() }
    res.setHeader('Content-Type', file.endsWith('.js') ? 'text/javascript' : file.endsWith('.css') ? 'text/css' : file.endsWith('.svg') ? 'image/svg+xml' : file.endsWith('.png') ? 'image/png' : 'text/html')
    res.end(fs.readFileSync(file))
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const url = process.env.ENERGY_URL || 'http://127.0.0.1:' + server.address().port + '/site/#/login'
  const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
  const output = path.join(__dirname, '../outputs')
  fs.mkdirSync(output, { recursive: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('console', m => { if (m.type() === 'error' && /shader|WebGLProgram/.test(m.text())) errors.push(m.text()) })
    await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 })
    await page.locator('.ec-ready canvas').waitFor({ timeout: 60000 })
    assert.equal(await page.locator('.ec-brand b').innerText(), '驭能智充')
    assert.equal(await page.locator('.ec-brand b').evaluate(el => getComputedStyle(el).color), 'rgb(147, 197, 253)')
    assert((await page.locator('.ec-mark img').getAttribute('src')).includes('.svg'))
    const brandSvg = await page.locator('.ec-mark img').evaluate(async el => (await fetch(el.src)).text())
    assert(brandSvg.includes('#2563eb') && !brandSvg.includes('#16c1a3'))
    const stage = page.locator('.ec-stage'), hit = page.locator('.ec-core-hit')
    const getState = () => stage.evaluate(el => ({ ...el.dataset }))
    const resolution = await page.locator('.ec-stage canvas').evaluate(c => c.width / c.clientWidth)
    assert(resolution >= 0.75 && resolution <= 1.51, 'render resolution should respect device pixels and the quality budget: ' + resolution)
    assert.equal(await page.locator('.ec-scene-tools').count(), 0, 'scene control buttons were removed at the user request')
    await hit.focus(); await page.keyboard.press('p')
    await page.waitForTimeout(250)
    const pausedFrame = (await getState()).frame
    await page.waitForTimeout(350)
    assert.equal((await getState()).frame, pausedFrame, 'paused scene must stop rendering')
    await page.keyboard.press('p')
    await page.waitForFunction(frame => document.querySelector('.ec-stage').dataset.frame !== frame, pausedFrame)
    await page.getByPlaceholder('请输入账号').focus()
    await page.waitForFunction(() => document.querySelector('.ec-stage').dataset.motion === 'focused')
    assert(Number((await getState()).speed) <= 0.25, 'form input should quiet the scene')
    await page.getByRole('heading', { name: '欢迎回来' }).click()
    const box = await hit.boundingBox(), x = box.x + box.width * .45, y = box.y + box.height * .5
    const initial = await getState()
    await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + 125, y - 60, { steps: 12 }); await page.mouse.up()
    await page.waitForTimeout(200)
    const after = await getState()
    assert.notEqual(initial.rotation, after.rotation)
    assert.equal(after.pulse, undefined)
    await page.waitForTimeout(250)
    assert.notEqual((await getState()).rotation, after.rotation)
    await hit.click({ position: { x: box.width * .45, y: box.height * .5 } })
    assert.equal((await getState()).pulse, '1')
    await page.mouse.wheel(0, -120); await page.waitForTimeout(600)
    assert(Number((await getState()).zoom) > 1)
    await hit.focus(); await page.keyboard.press('Home'); await page.waitForTimeout(650)
    await hit.focus(); await page.keyboard.press('Home')
    await page.waitForFunction(() => document.querySelector('.ec-stage').dataset.zoom === '1.000')
    await page.waitForTimeout(1800)
    await page.screenshot({ path: path.join(output, 'energy-login-desktop.png'), fullPage: true })
    const layout = () => page.evaluate(() => {
      const panel = document.querySelector('.ec-panel-shell').getBoundingClientRect()
      const footer = document.querySelector('.ec-footer').getBoundingClientRect()
      return { overflow: document.documentElement.scrollWidth > innerWidth, overlap: panel.bottom > footer.top, panelLeft: panel.left, panelRight: panel.right, width: innerWidth }
    })
    for (const width of [1440, 1024, 820, 768, 736, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 }); await page.waitForTimeout(100)
      const result = await layout()
      assert(!result.overflow && !result.overlap && result.panelLeft >= 0 && result.panelRight <= width, JSON.stringify(result))
    }
    await page.screenshot({ path: path.join(output, 'energy-login-mobile.png'), fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.evaluate(() => scrollTo(0, 0))
    const inputTop = await page.getByPlaceholder('请输入账号').evaluate(el => el.getBoundingClientRect().top)
    assert(inputTop < 650, 'phone login account must be visible in the first screen: ' + inputTop)
    assert.equal(await hit.evaluate(el => getComputedStyle(el).pointerEvents), 'none', 'mobile scene must allow normal page scrolling')
    await page.screenshot({ path: path.join(output, 'energy-login-phone-first-screen.png') })
    await page.setViewportSize({ width: 1440, height: 1000 })
    if (!process.env.ENERGY_URL) {
      await page.getByPlaceholder('请输入账号').fill('demo')
      await page.getByPlaceholder('请输入密码').fill('Demo123456!')
      await fillDemoCaptcha(page)
      await page.locator('.login-actions button').click()
      await page.waitForURL('**/#/index')
      assert.equal(await page.locator('.ec-stage canvas').count(), 0)
      await page.locator('.avatar-wrapper').click()
      await page.getByText('退出登录', { exact: true }).click()
      await page.getByRole('button', { name: '确定', exact: true }).click()
      await page.waitForURL('**/#/login')
      await page.locator('.ec-ready canvas').waitFor()
      assert.equal(await page.locator('.ec-stage canvas').count(), 1)
    }
    const blocked = await browser.newPage()
    await blocked.route('**/vendor/three-r160.min.js', route => route.abort())
    await blocked.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 })
    await blocked.getByText('能量核心 · 静态展示', { exact: true }).waitFor()
    assert(await blocked.locator('.ec-fallback').isVisible())
    assert(await blocked.locator('.login-actions button').isEnabled())
    await blocked.close()
    const phone = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
    await phone.goto(url)
    await phone.locator('.ec-ready canvas').waitFor()
    const touch = await phone.context().newCDPSession(phone)
    const target = await phone.locator('.ec-core-hit').boundingBox()
    const sx = Math.round(target.x + target.width / 2), sy = Math.round(target.y + target.height * .8)
    await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: sx, y: sy }] })
    for (let step = 1; step <= 6; step++) {
      await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: sx, y: sy - step * 20 }] })
      await phone.waitForTimeout(25)
    }
    await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await phone.waitForFunction(() => scrollY > 40)
    await touch.detach()
    await phone.close()
    const reduced = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
    await reduced.goto(url)
    await reduced.locator('.ec-ready canvas').waitFor()
    await reduced.waitForTimeout(500)
    const resting = await reduced.locator('.ec-stage').evaluate(el => ({ frame: el.dataset.frame, rotation: el.dataset.rotation }))
    await reduced.mouse.move(400, 500)
    await reduced.waitForTimeout(400)
    assert.deepEqual(await reduced.locator('.ec-stage').evaluate(el => ({ frame: el.dataset.frame, rotation: el.dataset.rotation })), resting, 'reduced motion must rest, including pointer parallax')
    await reduced.locator('.ec-core-hit').click()
    await reduced.getByText('能量已连接', { exact: true }).waitFor()
    await reduced.waitForTimeout(250)
    assert.equal(await reduced.locator('.ec-stage').getAttribute('data-frame'), resting.frame)
    await reduced.emulateMedia({ reducedMotion: 'no-preference' })
    await reduced.waitForFunction(frame => document.querySelector('.ec-stage').dataset.frame !== frame, resting.frame)
    await reduced.locator('.ec-core-hit').focus(); await reduced.keyboard.press('p')
    await reduced.emulateMedia({ reducedMotion: 'reduce' })
    await reduced.emulateMedia({ reducedMotion: 'no-preference' })
    await reduced.waitForTimeout(450)
    const userPausedFrame = await reduced.locator('.ec-stage').getAttribute('data-frame')
    await reduced.waitForTimeout(250)
    assert.equal(await reduced.locator('.ec-stage').getAttribute('data-frame'), userPausedFrame, 'media preference changes must preserve explicit pause')
    await reduced.locator('.ec-stage canvas').evaluate(canvas => canvas.getContext('webgl2').getExtension('WEBGL_lose_context').loseContext())
    await reduced.getByText('能量核心 · 静态展示', { exact: true }).waitFor()
    assert(await reduced.locator('.ec-fallback').isVisible())
    assert(await reduced.locator('.login-actions button').isEnabled())
    await reduced.close()
    assert.deepEqual(errors, [])
    console.log('PASS adaptive canvas; no scene control buttons; keyboard pause/resume/reset; quiet form input; drag/inertia/click/zoom; desktop/tablet/phone layouts; first-screen mobile input and touch scrolling; reduced-motion rest, preference changes and explicit pause; ' + (process.env.ENERGY_URL ? '' : 'login/logout remount; ') + 'runtime/context failure fallback; no page/shader errors')
  } finally { await browser.close(); server.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
