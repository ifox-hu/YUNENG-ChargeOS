const assert = require('node:assert/strict')
const fs = require('node:fs')
const http = require('node:http')
const path = require('node:path')
const { fillDemoCaptcha } = require('./demo-captcha-helper.cjs')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE ||
  'C:/Users/Lenovo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')

const root = path.resolve(process.env.DEMO_BUILD_ROOT || path.join(__dirname, '../site'))
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.png': 'image/png' }

async function main() {
  const server = http.createServer((req, res) => {
    const pathname = new URL(req.url, 'http://local').pathname.replace(/^\/site\//, '/')
    const file = path.resolve(root, '.' + (pathname === '/' ? '/index.html' : pathname))
    if (!file.startsWith(root + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) {
      res.writeHead(404).end()
      return
    }
    res.setHeader('Content-Type', types[path.extname(file)] || 'application/octet-stream')
    fs.createReadStream(file).pipe(res)
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  let browser
  try {
    browser = await chromium.launch({ channel: 'msedge', headless: true })
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = [], backend = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => {
      if (/\/(prod-api|demo-api)\//.test(request.url())) backend.push(request.url())
    })
    const origin = process.env.DEMO_URL || 'http://127.0.0.1:' + server.address().port + '/site/'
    const base = origin.replace(/\/?$/, '/') + '#'
    const sidebar = page.locator('.sidebar-container')
    const alarmPanel = page.getByTestId('alarm-events')
    async function login(username, password) {
      await page.getByPlaceholder('请输入账号').fill(username)
      await page.getByPlaceholder('请输入密码').fill(password)
      await fillDemoCaptcha(page)
      await page.locator('.login-actions button').click()
      await page.waitForURL('**/#/index')
      await page.locator('.update-time').waitFor()
    }

    await page.goto(base + '/login')
    assert.equal(await page.getByPlaceholder('请输入账号').inputValue(), 'admin')
    const password = page.getByPlaceholder('请输入密码')
    assert.equal(await password.inputValue(), '')
    await page.getByRole('button', { name: '一键填入', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('input[placeholder="请输入右侧验证码"]').value.length === 4)
    assert.equal(await password.inputValue(), 'admin123')
    assert.equal(await password.getAttribute('type'), 'password')
    await page.locator('.login-actions button').click()
    await page.waitForURL('**/#/index')
    await page.getByText('admin · 全平台', { exact: false }).waitFor()
    await page.getByRole('button', { name: '运营商经营', exact: true }).waitFor()
    await page.goto(base + '/system/tenant')
    await page.locator('button').filter({ hasText: '运营商开户' }).waitFor({ timeout: 8000 }).catch(async error => {
      throw new Error(JSON.stringify({ url: page.url(), body: (await page.locator('body').innerText()).slice(0, 800), errors }), { cause: error })
    })
    await page.goto(base + '/operate/fault')
    await alarmPanel.getByText('DEMO-PLATFORM-CITY-OFFLINE', { exact: true }).waitFor()
    await alarmPanel.getByRole('button', { name: '新建异步告警' }).waitFor()

    const devices = page.getByRole('dialog', { name: '站点设备' })
    await page.goto(base + '/operate/station')
    await page.locator('button.el-button--primary').filter({ hasText: '新增' }).click()
    const stationForm = page.getByRole('dialog', { name: '添加站点' })
    await stationForm.getByPlaceholder('请输入站点名称').fill('浏览器验收充电站')
    await stationForm.getByPlaceholder('请输入站点编号').fill('QA-UI-01')
    await stationForm.getByPlaceholder('请输入地址').fill('验收路 1 号')
    await stationForm.getByPlaceholder('请输入所属地区代码').fill('330100')
    await stationForm.getByPlaceholder('请输入经度').fill('120.1')
    await stationForm.getByPlaceholder('请输入纬度').fill('30.2')
    await stationForm.getByPlaceholder('请选择平台类型').click()
    await page.locator('.el-select-dropdown:visible li').filter({ hasText: /汽车|四轮/ }).first().click()
    await stationForm.locator('button').filter({ hasText: /确\s*定/ }).click()
    await devices.getByText('浏览器验收充电站').waitFor()
    await devices.getByRole('button', { name: '添加充电桩' }).click()
    const deviceForm = devices.getByRole('region', { name: '添加充电桩' })
    const field = label => deviceForm.locator('.el-form-item').filter({ has: page.locator('label', { hasText: label }) }).locator('input')
    await field('桩编号').fill('SIM-UI-01')
    await field('桩名称').fill('验收双枪桩')
    await field('额定电压').fill('750')
    await field('额定电流').fill('200')
    await field('最大功率').fill('120')
    await deviceForm.getByPlaceholder('选择本运营商费率').click()
    await page.locator('.el-select-dropdown:visible li').first().click()
    await devices.getByRole('button', { name: '保存充电桩和枪口' }).click()
    await devices.getByRole('button', { name: '验收双枪桩 离线' }).waitFor()
    await devices.getByText('2 个枪口', { exact: true }).waitFor()
    await devices.getByRole('button', { name: '启动模拟' }).click()
    await devices.getByRole('button', { name: '验收双枪桩 在线' }).waitFor()
    await devices.getByText('2 个空闲', { exact: true }).waitFor()
    assert.equal(await devices.getByText('暂无记录', { exact: true }).count(), 0)
    await devices.getByRole('link', { name: '查看告警' }).click()
    await devices.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: '模拟设备告警' }).click()
    const alarmForm = page.getByRole('dialog', { name: '模拟设备告警' })
    assert.equal(await alarmForm.getByPlaceholder('例如 202312121').inputValue(), 'SIM-UI-01')
    await alarmForm.locator('textarea').fill('检查验收桩通信')
    await alarmForm.getByRole('button', { name: '生成告警' }).click()
    const newTicket = page.getByRole('dialog', { name: '工单详情与处理记录' })
    await newTicket.getByText('SIM-UI-01', { exact: true }).waitFor()
    for (const [action, title, note] of [
      ['分配处理人', '分配工单', '分配值班人员'],
      ['开始处理', '开始处理', '检查模拟桩状态'],
      ['提交解决结果', '提交解决结果', '已确认心跳恢复'],
      ['确认关闭', '确认关闭', '验收通过']
    ]) {
      await newTicket.getByRole('button', { name: action }).click()
      const actionDialog = page.getByRole('dialog', { name: title, exact: true })
      if (action === '分配处理人') {
        await actionDialog.getByPlaceholder('选择同租户处理人').click()
        await page.locator('.el-select-dropdown:visible li').first().click()
      }
      await actionDialog.getByPlaceholder('填写处理步骤或解决结果').fill(note)
      await actionDialog.getByRole('button', { name: '确认', exact: true }).click()
      await newTicket.getByText(note, { exact: true }).waitFor()
    }
    await newTicket.getByText('已关闭', { exact: true }).waitFor()
    await newTicket.getByRole('button', { name: 'Close' }).click()

    await page.locator('.avatar-wrapper').click()
    await page.getByText('退出登录', { exact: true }).click()
    await page.getByRole('button', { name: '确定', exact: true }).click()
    await page.waitForURL('**/#/login', { waitUntil: 'load' })
    await page.waitForFunction(() => !document.cookie.includes('Demo-Token='))
    assert.equal(await page.getByPlaceholder('请输入账号').inputValue(), 'admin')
    assert.equal(await page.getByPlaceholder('请输入密码').inputValue(), '')

    await login('demo', 'Demo123456!')
    await page.getByText('demo · 本运营商', { exact: true }).waitFor()
    await page.getByTestId('overview-scope').getByText('城际快充 · 演示', { exact: true }).waitFor()
    const tenantCookie = (await page.context().cookies()).find(cookie => cookie.name === 'Demo-Tenant')
    assert.equal(tenantCookie.value, '887001')
    assert.equal(await page.locator('.shortcut-card').count(), 2)
    const businessLinks = await sidebar.locator('a[href*="#/operate/"]').evaluateAll(links =>
      links.map(link => link.hash).sort())
    assert.deepEqual(businessLinks, ['#/operate/fault', '#/operate/order', '#/operate/station'])
    assert.equal(await sidebar.locator('a[href*="#/system/"],a[href*="#/operations/"]').count(), 0)
    assert.equal(await page.getByRole('button', { name: '重置数据', exact: true }).count(), 0)
    await page.goto(base + '/index?stationId=88700101')
    await page.getByRole('button', { name: '查看站点详情' }).click()
    await page.getByRole('dialog', { name: '站点详情' }).getByRole('button', { name: '查看设备' }).click()
    await devices.getByText('24 个枪口', { exact: true }).waitFor()
    assert.equal(await devices.getByRole('button', { name: '添加充电桩' }).count(), 0)
    await devices.getByRole('button', { name: 'Close' }).click()
    await devices.waitFor({ state: 'hidden' })
    for (const route of ['/system/tenant', '/operations/screen']) {
      await page.goto(base + route)
      await page.waitForURL('**/#/404')
    }

    await page.goto(base + '/operate/station')
    await page.getByText('【演示】城际·中心广场站', { exact: true }).first().waitFor()
    assert.equal(await page.locator('button.el-button--primary').filter({ hasText: '新增' }).count(), 0)
    assert.equal(await page.locator('.el-table__row').filter({ hasText: '滨江示范充电站' }).count(), 0)
    const stationRow = page.locator('.el-table__row').filter({ hasText: '城际·中心广场站' }).first()
    await stationRow.getByRole('button', { name: '查看设备' }).click()
    await devices.getByText('24 个枪口', { exact: true }).waitFor()
    const ports = devices.getByRole('region', { name: '枪口状态' })
    assert.equal(await ports.getByText('离线', { exact: true }).count(), 2)
    await devices.getByRole('button', { name: '【演示】城际·中心广场站 9 在线' }).click()
    await ports.getByText('连接器异常（演示）', { exact: true }).waitFor()
    await devices.getByRole('link', { name: '查看告警' }).click()
    await devices.waitFor({ state: 'hidden' })
    await alarmPanel.getByText('暂无数据', { exact: true }).waitFor()
    await page.getByRole('button', { name: '返回站点设备' }).click()
    await devices.getByText('24 个枪口', { exact: true }).waitFor()
    await ports.getByText('连接器异常（演示）', { exact: true }).waitFor()
    await devices.getByRole('button', { name: '【演示】城际·中心广场站 1 离线', exact: true }).click()
    await devices.getByRole('link', { name: '查看告警' }).click()
    await page.waitForURL(url => new URLSearchParams(url.hash.split('?')[1]).get('pileId') === 'DEMO_OV_CITY_1_P01')
    const cityAlarm = alarmPanel.locator('.el-table__row').filter({ hasText: 'DEMO-PLATFORM-CITY-OFFLINE' })
    await cityAlarm.waitFor()
    assert.equal(await alarmPanel.locator('.el-table__body-wrapper .el-table__row').count(), 1)
    await cityAlarm.getByRole('button', { name: '工单', exact: true }).click()
    const ticket = page.locator('.el-dialog:visible').filter({ hasText: '工单详情' })
    await ticket.waitFor()
    assert.equal(await ticket.getByRole('button', { name: '分配处理人' }).count(), 0)
    await page.goto(base + '/operate/order')
    await page.locator('.el-table__row').first().getByRole('button', { name: '详情' }).click()
    await page.waitForURL('**/#/operate/ordertDetail/?**')
    await page.goto(base + '/operate/fault')
    await cityAlarm.waitFor()
    assert.equal(await alarmPanel.getByText('DEMO-ALARM-DEAD', { exact: true }).count(), 0)
    assert.equal(await alarmPanel.getByRole('button', { name: /新建异步告警|重放/ }).count(), 0)
    await page.locator('.fault-page > .el-table .el-table__row').filter({ hasText: 'DEMO_OV_CITY_' }).first().waitFor()
    await page.context().addCookies([{ ...tenantCookie, value: '9999' }])
    await page.reload()
    await page.getByText('demo · 本运营商', { exact: true }).waitFor()
    assert.equal((await page.context().cookies()).find(cookie => cookie.name === 'Demo-Tenant').value, '887001')

    assert.deepEqual(errors, [])
    assert.deepEqual(backend, [])
    console.log('PASS platform onboarding, tenant isolation, station creation, dual-gun registration, simulation, alarm and ticket')
  } finally {
    if (browser) await browser.close()
    server.close()
  }
}

main().catch(error => { console.error(error); process.exitCode = 1 })
